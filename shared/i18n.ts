export function translate(message: string, locale: LocaleId): string {
  if (locale === 'ru' || !message) return message
  const key = messages[message]
  if (key) {
    const value = en[key]
    return typeof value === 'string' ? value : message
  }
  const many = /^Не больше (\d+) файлов за раз$/.exec(message)
  if (many) return `No more than ${many[1]} files at once`
  const named = (label: string) => {
    const key = fieldNames[label]
    const value = key ? en[key] : label
    return typeof value === 'string' ? value : label
  }
  const range = /^Поле «(.+)» вне диапазона$/.exec(message)
  if (range) return `Field “${named(range[1])}” is out of range`
  const long = /^Поле «(.+)» слишком длинное$/.exec(message)
  if (long) return `Field “${named(long[1])}” is too long`
  return message
}
